# Q2 step 3: generates X2Lib/Offline/X2OfflineJuneQuestMig.h, the tables the v21 save rung reads.
# The rung runs from CX2OfflineDB::Open, before the quest Lua loads, and March's quest files exist nowhere at
# run time after the flip, so both sides are carried as constants (same shape as cap99_gen.py / v16).
# usage: python q2_gen.py [--check]     (--check: compare with the file on disk, write nothing)
#        python q2_gen.py simulate <copy of a pre-v21 save>   (the MIG lines the rung should write)
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import q2_census as c

OUT = os.path.join(c.TRUNK, "X2Lib", "Offline", "X2OfflineJuneQuestMig.h")

def build():
    mq, ms = c.march(); jq, js = c.june()
    typ = lambda t: c.r(t.get("m_eQuestType"))
    june_ids = sorted(jq)
    # Reset: a quest both sides have whose sub-quest list, or any sub-quest's clear type / condition, differs
    # (the census's P_SUBS_CHANGED test, applied to every common quest, not only the save's).
    # m_eDungeonID is compared as the set each loader stores (Q2 review: March's {0} = June's absent key = empty).
    reset = []
    for q in sorted(set(mq) & set(jq)):
        mv, jv = c.ints(mq[q].get("m_vecSubQuest")), c.ints(jq[q].get("m_vecSubQuest"))
        if mv != jv or any(c.subsig(ms.get(s), True) != c.subsig(js.get(s)) for s in jv):
            reset.append(q)
    # Epic next link: a March epic June dropped -> the epics June's after-list opens from the same March
    # predecessor instead (12005 sat between 12000 and 12010; June's 12000 opens 12020).
    nxt = []
    for x in sorted(q for q in mq if q not in jq and typ(mq[q]) == "QT_EPIC"):
        for p in sorted(p for p, t in mq.items() if x in c.ints(t.get("m_iAfterQuestID")) and p in jq):
            for y in c.ints(jq[p].get("m_iAfterQuestID")):
                if y in jq and typ(jq[y]) == "QT_EPIC" and y not in c.ints(mq[p].get("m_iAfterQuestID")) and (x, y) not in nxt:
                    nxt.append((x, y))
    accept_reward = sorted(q for q, t in jq.items() if t.get("m_vecAcceptRewardItem") is not None)
    return june_ids, reset, nxt, accept_reward, len(mq), len(jq)

def render(june_ids, reset, nxt, accept_reward, nm, nj):
    L = []
    w = L.append
    w("#ifdef SERV_IRUHADEV_JUNE_QUEST_DATA")
    w("#pragma once")
    w("")
    w("//////////////////////////////////////////////////////////////////////////")
    w("// Author: Iruha")
    w("// Date: 2026-10-19")
    w("// Description: June quest system Phase Q2 - the tables the one-way quest save migration")
    w("//              (CX2OfflineDB::Migrate, schema v21) reads. GENERATED by")
    w("//              june2017_re/quest_plan/q2_gen.py - do not edit by hand.")
    w("//")
    w("//              The rung runs from CX2OfflineDB::Open, before the quest Lua loads, and after")
    w("//              this phase data036 ships June's quest files, so both sides are constants:")
    w("//")
    w("//                MARCH  data036 FieldQuest / FieldSubQuest / AccountQuest, March 2014 (%d quests)" % nm)
    w("//                       (24965799\\kom_contents_bytecode\\data036_kom, shipped bytecode)")
    w("//                JUNE   the same three files, June 2017 (%d quests)" % nj)
    w("//                       (june_src_fixed/data036_kom/*.src.lua)")
    w("//")
    w("//              JUNE_QUEST_IDS   every quest id June's client loads from those files, sorted")
    w("//              RESET_QUEST_IDS  quests both have whose sub-quest list or a sub-quest's clear")
    w("//                               condition changed: saved progress restarts at 0 (user, 2026-10-19)")
    w("//              EPIC_NEXT        a March epic June dropped -> the epic June opens instead from")
    w("//                               the same predecessor; granted fresh when the dropped one was")
    w("//                               in progress (user, 2026-10-19)")
    w("//              %d June quests carry m_vecAcceptRewardItem; no EPIC_NEXT target is one of them." % len(accept_reward))
    w("//////////////////////////////////////////////////////////////////////////")
    w("")
    w("namespace X2OfflineJuneQuestMig")
    w("{")
    w("\tenum")
    w("\t{")
    w("\t\tJUNE_QUEST_COUNT\t= %d," % len(june_ids))
    w("\t\tRESET_QUEST_COUNT\t= %d," % len(reset))
    w("\t\tEPIC_NEXT_COUNT\t\t= %d," % len(nxt))
    w("\t};")
    w("")
    def arr(name, vals):
        w("\tstatic const int %s[] =" % name)
        w("\t{")
        for i in range(0, len(vals), 12):
            w("\t\t" + " ".join("%d," % v for v in vals[i:i + 12]))
        w("\t};")
        w("")
    arr("JUNE_QUEST_IDS", june_ids)
    arr("RESET_QUEST_IDS", reset)
    w("\tstruct KEpicNext { int m_iDropped; int m_iNext; };")
    w("")
    w("\tstatic const KEpicNext EPIC_NEXT[] =")
    w("\t{")
    for x, y in nxt: w("\t\t{ %d, %d }," % (x, y))
    w("\t};")
    w("}")
    w("")
    w("#endif SERV_IRUHADEV_JUNE_QUEST_DATA")
    return "\r\n".join(L) + "\r\n"

def simulate(save):
    # What CX2OfflineDB::MigrateQuestsToJune does to <save> (a copy of a pre-v21 els_db.sql), one line per unit and category,
    # in the rung's order - the reference its [JUNE_QUEST] MIG lines are checked against.
    import sqlite3, collections
    J, R, N, _, _, _ = build(); J = set(J); R = set(R)
    db = sqlite3.connect(save)
    U = collections.defaultdict(lambda: {"q": set(), "s": set(), "c": set()})
    for u, q in db.execute("select unit_uid, quest_id from unit_quest"): U[u]["q"].add(q)
    for u, q in db.execute("select distinct unit_uid, quest_id from unit_subquest"): U[u]["s"].add(q)
    for u, q in db.execute("select unit_uid, quest_id from unit_quest_complete"): U[u]["c"].add(q)
    T = collections.Counter()
    for u in sorted(U):
        k = U[u]; d = []; g = []; r = []
        for q in sorted(set(k["q"])):
            if q in J:
                if q in R and q in k["s"]: r.append(q)
                continue
            d.append(q); k["q"].discard(q)
            for x, y in N:
                if x == q and y not in k["q"] and y not in k["c"]: g.append("%d->%d" % (x, y)); k["q"].add(y)
        dc = [q for q in sorted(k["c"]) if q not in J]
        for n, v in (("in-progress dropped (no June templet)", d), ("epic next accepted", g),
                     ("progress reset (sub-quests changed)", r), ("completed dropped (no June templet)", dc)):
            if v: print("[JUNE_QUEST] MIG unit %d %s %d: %s" % (u, n, len(v), ",".join(map(str, v)))); T[n] += len(v)
    print("%d unit(s); %s" % (len(U), dict(T)))

def main():
    if len(sys.argv) > 2 and sys.argv[1] == "simulate":
        return simulate(sys.argv[2])
    june_ids, reset, nxt, ar, nm, nj = build()
    bad = [y for _, y in nxt if y in ar]
    if bad: sys.exit("EPIC_NEXT target with an accept reward: %s" % bad)
    txt = render(june_ids, reset, nxt, ar, nm, nj)
    print("june ids %d, reset %d, epic next %d: %s" % (len(june_ids), len(reset), len(nxt), nxt))
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT, "rb").read() == txt.encode("ascii")
        print("CHECK", "PASS" if same else "FAIL"); sys.exit(0 if same else 1)
    open(OUT, "wb").write(txt.encode("ascii"))
    print("wrote", OUT)

if __name__ == "__main__":
    main()
