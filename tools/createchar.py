def die(msg):
    raise SystemExit('createchar: ' + msg)


def resolve_class(arg):
    if arg.isdigit():
        n = int(arg)
        if n not in CLASSES:
            die('class id %d is not a UNIT_CLASS (see CLASSES in this file)' % n)
        return n
    key = re.sub(r'^uc_', '', arg.lower().replace('-', '_').replace(' ', '_'))
    hits = [i for i, n in CLASSES.items() if key in n.lower()]
    exact = [i for i in hits if CLASSES[i].lower() == key]
    hits = exact or hits
    if len(hits) != 1:
        die('class %r matches %s' % (arg, ', '.join('%d %s' % (i, CLASSES[i]) for i in hits) or 'nothing'))
    return hits[0]


def exp_for(level):
    # June's ExpTable since Atlas A2 (data036 carries it; the save was migrated onto it, schema v16).
    # march_exptable.tsv stays as the migration's source record.
    with open(os.path.join(HERE, 'data', 'june_exptable.tsv')) as f:
        table = dict(tuple(map(int, l.split())) for l in f if l.strip() and not l.startswith('#'))
    if level not in table or level > 99:
        die('level %d is outside 1-99 (cap 99, June ExpTable)' % level)
    return table[level]


# June SKILL_TYPE values that go on the bar (CX2OfflineSkill::SeedJuneAutoLearn): 5 BUFF, 6 ACTIVE, 7 SPECIAL_ACTIVE,
# 14..16 SPECIAL_ACTIVE_GRADE_1..3.
CASTABLE_TYPES = (5, 6, 7, 14, 15, 16)
SLOT_COUNT_PER_SET = 4


def init_sp(level):
    # June GetCalcInitSkillPoint 32205790 (generated by june2017_re/s3_autolearn_gen.py from June's SkillData.lua).
    with open(os.path.join(HERE, 'data', 'june_skill_init_sp.tsv')) as f:
        rows = dict(tuple(int(x) for x in l.split('	')) for l in f.read().splitlines()[1:] if l)
    if level not in rows:
        die('level %d is outside 1-99 (June SP table)' % level)
    return rows[level]


def autolearn_rows(cls, level):
    # (skill_id, skill_type) of the class's free tree rows that the level allows, in tree-file order.
    out = []
    with open(os.path.join(HERE, 'data', 'june_skill_autolearn.tsv')) as f:
        for l in f.read().splitlines()[1:]:
            if not l:
                continue
            ucls, sid, req, stype = (int(x) for x in l.split('	')[:4])
            if ucls == cls and req <= level:
                out.append((sid, stype))
    return out


def seed_skills(c, uid, cls, level):
    """Grant the class's free rows the unit lacks; castable ones take free A slots. Returns (granted, slotted)."""
    have = {sid for (sid,) in c.execute('SELECT skill_id FROM unit_skill WHERE unit_uid=? AND level>0', (uid,))}
    used = {sl for (sl,) in c.execute('SELECT slot FROM unit_skill WHERE unit_uid=? AND level>0 AND slot>=0', (uid,))}
    granted = slotted = 0
    for sid, stype in autolearn_rows(cls, level):
        if sid in have:
            continue
        slot = -1
        if stype in CASTABLE_TYPES:
            free = [s for s in range(SLOT_COUNT_PER_SET) if s not in used]
            if free:
                slot = free[0]
                used.add(slot)
                slotted += 1
        c.execute('INSERT OR REPLACE INTO unit_skill(unit_uid,skill_id,level,csp,slot) VALUES(?,?,1,0,?)', (uid, sid, slot))
        granted += 1
    return granted, slotted


