function TableCopy(t)
	-- SERV_IRUHADEV_RANOX_PORT (2026-09-18): Phase 9 (Secret Hell) -- this body
	-- is a RECONSTRUCTION, not a decompile. The vendored ljd decompiler
	-- (elstools/vendor/ljd) crashes on this function's generic-for loop with
	-- "assert iterator.opcode in (ins.ITERC.opcode, ins.ITERN.opcode)"
	-- (ljd/ast/builder.py:375) -- a real bytecode-parsing limitation in the
	-- vendored tool, confirmed by instrumenting the assert: the instruction it
	-- inspects is USETV (opcode 44), not an ITER-family opcode at all, so this
	-- isn't a simple missing-opcode fix. Reconstructed from direct evidence,
	-- not guessed: the pseudo-asm for this prototype shows exactly
	-- "1 args, 0 upvalues, 9 slots" then TNEW (new empty table) immediately
	-- followed by GGET _env["pairs"] and a CALL passing the sole argument to
	-- it -- i.e. this function opens a table and iterates the argument with
	-- pairs(). Both call sites in this same file/its sibling
	-- (SECRET_SCENE_DUMMY.lua) use it as `g_arrSummonPos = TableCopy(g_arrSummonPosOrigin)`
	-- and `#TableCopy(slot3)` / `slot5 = TableCopy(slot3)` -- both require a
	-- returned, #-countable shallow copy, which is the only behavior consistent
	-- with the bytecode shape above. This is the single, unambiguous
	-- implementation of a function named TableCopy with that evidence; nothing
	-- about drop rates, stats, or dungeon-specific tuning was invented here.
	local copy = {}
	for k, v in pairs(t) do
		copy[k] = v
	end
	return copy
end

