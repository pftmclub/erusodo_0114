		if slot1:GetEffectSet() ~= nil then
			slot4:PlayEffectSet_LUA("EffectSet_MOUNT_FIREBIRD_AttackA_Fire", slot2)
		end

		slot3.x = slot3.x + 0.07
		slot3.y = slot3.y + 1

