function SMITH_RUNNER_START_STATE_START(slot0, slot1, slot2)
	if slot2:GetKeyCode() > 0 then
		slot1:SetInt_LUA(8, 0)
		slot1:SetInt_LUA(9, 10)
		slot2:StateChange_LUA("SMITH_RUNNER_REGEN_WAIT", true)
	elseif slot1:GetNowStageIndex() == 2 then
		slot2:StateChange_LUA("SMITH_RUNNER_JUMP_START", true)
	end
end

