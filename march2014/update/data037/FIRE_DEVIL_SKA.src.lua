function GetUser(slot0, slot1)
	-- SERV_IRUHADEV_RANOX_PORT (2026-09-29): elstools' decompile dropped this
	-- assignment and inlined the call into the condition; the port carried
	-- the bug verbatim. Bytecode-confirmed: decompile_verdicts.tsv,
	-- FIRE_DEVIL_SKA.src.lua::GetUser, dropped-assignment, seed 1,
	-- POISON_READ slot2@L2051.
	slot2 = slot1:GetTargetUser()

	if slot2 == nil then
		slot2 = slot0:GetUserUnit(slot1:GetRandVal() % slot0:GetUserUnitNum_LUA())
	end

	-- SERV_IRUHADEV_RANOX_PORT (2026-09-18): June2017's fallback to
	-- slot0:GetHostGameUnit() when there's no current target is omitted --
	-- that method isn't bound in this March2014 client (checked X2Lib/KTDXLIB,
	-- not found; calling it would raise a Lua error each time this runs). slot2
	-- simply stays nil in that case, same shape as this plan's other
	-- host-unit-fallback omissions.

	return slot2
end

function FIRE_DEVIL_SKA_COMMON_FRAME_FUNC(slot0, slot1, slot2)
	if slot2 ~= nil and slot2:GetFlag_LUA(0) == false and slot2:GetNowHP() < slot2:GetMaxHP() * 0.7 then
		slot2:StateChange_LUA("FIRE_DEVIL_SKA_PHASE_CHANGE_START", true)
	end
end
