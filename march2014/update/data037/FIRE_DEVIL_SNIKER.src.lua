function FIRE_DEVIL_SNIKER_ATTACK_B_READY_JUMP_TO_TARGET(slot0, slot1, slot2)
	slot3 = slot2:GetPos()
	slot4 = slot2:GetDirVector()
	slot8 = 1
	slot9 = true

	if slot1:GetUserUnit(slot2:GetRandVal() % slot1:GetUserUnitNum_LUA()) ~= nil then
		slot3 = slot7:GetPos()
		slot3.y = slot7:GetLandPosition_LUA().y

		if slot2:IsRightTarget_LUA(slot2, slot3) == true then
			slot8 = -1
		end
		-- SERV_IRUHADEV_RANOX_PORT (2026-09-18): June2017's elseif fallback to
		-- slot1:GetHostGameUnit() is omitted -- that method isn't bound in this
		-- March2014 client (checked X2Lib/KTDXLIB, not found; calling it would
		-- raise a Lua error each time this frame-move fires). slot8/slot4 simply keep the
		-- defaults already set above when there's no regular target.
	end

	slot2:SetIsRight(slot9)
	slot2:SetPosition(slot3, slot9)
end
