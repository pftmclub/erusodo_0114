function FIRE_DEVIL_BERSERKER_VER_GATEWAY_START_READY_STATE_START(slot0, slot1, slot2)
	-- SERV_IRUHADEV_RANOX_PORT (2026-09-18): both slot1:GetNowStateID_LUA() and
	-- slot1:GetIsLastStage() are omitted -- neither is bound in this March2014
	-- client (checked X2Lib/KTDXLIB; GetNowStateID_LUA isn't bound under that
	-- name for any class, GetIsLastStage doesn't exist anywhere in the C++
	-- source at all). This VER_GATEWAY_START_READY state is a GateWay-line
	-- variant this Phase's own FinalHall content never enters (no FinalHall
	-- file references "VER_GATEWAY" at all) -- it's ported here only because
	-- this whole unit-definition file is shared with Phase 8 (GateWay), which
	-- reuses it without re-porting per this plan's own instruction. The call
	-- would only actually fault once GateWay's own dungeon files drive an NPC
	-- into this state, not for anything in this phase. Phase 8 should re-check
	-- this edit once its own GateWay content lands, since the semantics below
	-- are a guess made without being able to exercise the real code path.
	-- June2017's logic only skips the StateChange_LUA call when
	-- GetIsLastStage() is true (deferring the start to whatever separately
	-- drives the dungeon's actual last stage); since that check can't be
	-- evaluated here, this always transitions to START instead of risking the
	-- NPC getting stuck un-activated. The SetFlag_LUA(9, ...) "is this the
	-- last GateWay stage" bookkeeping is also dropped, since it
	-- depended on the same unbound call.
	slot2:StateChange_LUA("FIRE_DEVIL_BERSERKER_START", true)
end

